const BY_ID: ReadonlyMap<string, ExerciseDefinition> = new Map(EXERCISES.map((e) => [e.id, e]))

export function getExercise(id: string): ExerciseDefinition | undefined {
  return BY_ID.get(id)
}

export function getExercisesByCategory(category: ExerciseCategory): ExerciseDefinition[] {
  return EXERCISES.filter((e) => e.category === category)
}

/** Equivalent exercises the user can swap in, resolved to full definitions. */
export function getSubstitutions(id: string): ExerciseDefinition[] {
  return (getExercise(id)?.substitutions ?? []).flatMap((s) => getExercise(s) ?? [])
}
